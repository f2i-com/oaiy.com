#!/usr/bin/env node
/**
 * Regenerate src/softn/guide.generated.ts, the SoftN writing guide the agent
 * reads, from softn.com's own Studio guide (apps/softn-studio/src/lib/agent/
 * guide.ts, Apache-2.0), so OAIY's agent is taught what SoftN Studio's
 * is, but for what OAIY's preview does (OAIY_PREVIEW). The output is
 * committed; run this after a SoftN update:
 *
 *   SOFTN_REPO=../softn.com node scripts/generate-softn-guide.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(process.env.SOFTN_REPO || join(here, '..', '..', 'softn.com'));
const guidePath = join(repo, 'apps/softn-studio/src/lib/agent/guide.ts');
const composer = readFileSync(join(repo, 'packages/@softn/core/src/bundle/source-composer.ts'), 'utf8');
const stdlib = /export const SOFTN_PY_STDLIB_IMPORTS[^=]*=\s*(\[[^\]]*\])/.exec(composer)?.[1];
if (!stdlib) throw new Error('SOFTN_PY_STDLIB_IMPORTS not found in @softn/core');

let source = readFileSync(guidePath, 'utf8');
source = source.replace(/import\s*\{\s*SOFTN_PY_STDLIB_IMPORTS\s*\}\s*from\s*'@softn\/core';/, `const SOFTN_PY_STDLIB_IMPORTS = ${stdlib};`);
if (/from\s+'/.test(source)) throw new Error('guide.ts has imports this generator does not know how to satisfy');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const guide = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);

// Where Studio's preview and OAIY's differ: [Studio's words, OAIY's]. OAIY's preview is the hosted runtime, which
// runs every app with no capabilities and has no Allow button (its formlogic:init takes no declaration).
const OAIY_PREVIEW = [
  [
    'The preview withholds them until the person presses Allow in preview above the app, so these calls fail there until then;',
    'The preview grants no capabilities, so these calls fail there;',
  ],
];
const forOaiy = (text) =>
  OAIY_PREVIEW.reduce((out, [studio, oaiy]) => {
    if (!out.includes(studio)) throw new Error(`guide.ts no longer says "${studio}": say what OAIY's preview does in its place`);
    return out.replaceAll(studio, oaiy);
  }, text);
const variants = {
  JAVASCRIPT: forOaiy(guide.buildGuide({ python: false, torch: false, backend: false, style: 'clean' })),
  PYTHON: forOaiy(guide.buildGuide({ python: true, torch: false, backend: false, style: 'clean' })),
};
let commit = 'unknown';
try {
  const head = readFileSync(join(repo, '.git', 'HEAD'), 'utf8').trim();
  commit = head.startsWith('ref: ') ? readFileSync(join(repo, '.git', head.slice(5)), 'utf8').trim() : head;
} catch {
  /* not a git checkout */
}
const out = `// Generated by scripts/generate-softn-guide.mjs from softn.com
// (apps/softn-studio/src/lib/agent/guide.ts at ${commit.slice(0, 12)}),
// Copyright f2i-com, Apache License 2.0. Do not edit by hand.

export const SOFTN_GUIDE_JAVASCRIPT = ${JSON.stringify(variants.JAVASCRIPT)};

export const SOFTN_GUIDE_PYTHON = ${JSON.stringify(variants.PYTHON)};
`;
const target = join(here, '..', 'src', 'softn', 'guide.generated.ts');
writeFileSync(target, out);
console.log(`wrote ${target} (${(out.length / 1024).toFixed(1)} KiB)`);
